#!/usr/bin/env node
/**
 * Resolve release + build identity for Docker Compose / Vite bake.
 * Writes `.env.build` at the repo root for `docker compose --env-file`.
 *
 * Env overrides (optional): EKUM_VERSION, EKUM_BUILD_ID, EKUM_GIT_SHA,
 * EKUM_BUILT_AT, EKUM_DEPLOYMENT, EKUM_IMAGE_TAG.
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function git(command) {
  try {
    return execSync(command, { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function readVersionFile() {
  try {
    return readFileSync(join(root, 'VERSION'), 'utf8').trim();
  } catch {
    return '0.0.0-dev';
  }
}

/** Key=value from .env.docker (no export) so local/server flavour reaches the bake. */
function readDockerEnvKey(key) {
  try {
    const text = readFileSync(join(root, '.env.docker'), 'utf8');
    for (const line of text.split(/\r?\n/)) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const i = trimmed.indexOf('=');
      if (i <= 0) continue;
      if (trimmed.slice(0, i).trim() === key) {
        return trimmed.slice(i + 1).trim();
      }
    }
  } catch {
    // optional file
  }
  return '';
}

const version = process.env.EKUM_VERSION || readVersionFile() || '0.0.0-dev';
const gitSha = process.env.EKUM_GIT_SHA || git('git rev-parse HEAD') || 'unknown';
const shortSha = gitSha === 'unknown' ? 'unknown' : gitSha.slice(0, 7);
const builtAt = process.env.EKUM_BUILT_AT || new Date().toISOString();
const buildId =
  process.env.EKUM_BUILD_ID || `${builtAt.replace(/[:.]/g, '-')}-${shortSha}`;
const deploymentRaw =
  process.env.EKUM_DEPLOYMENT || readDockerEnvKey('EKUM_DEPLOYMENT') || 'test';
const deployment = deploymentRaw === 'production' ? 'production' : 'test';
const imageTag = process.env.EKUM_IMAGE_TAG || version;

const lines = [
  `# Generated by scripts/resolve-build-meta.mjs - do not commit`,
  `EKUM_VERSION=${version}`,
  `EKUM_BUILD_ID=${buildId}`,
  `EKUM_GIT_SHA=${gitSha}`,
  `EKUM_BUILT_AT=${builtAt}`,
  `EKUM_DEPLOYMENT=${deployment}`,
  `EKUM_IMAGE_TAG=${imageTag}`,
  `EKUM_GIT_SHORT_SHA=${shortSha}`,
  '',
];

const outPath = join(root, '.env.build');
writeFileSync(outPath, lines.join('\n'), 'utf8');

const meta = { version, buildId, gitSha, shortSha, builtAt, deployment, imageTag };
process.stdout.write(`${JSON.stringify(meta)}\n`);
